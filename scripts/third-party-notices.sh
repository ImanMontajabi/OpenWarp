#!/bin/sh
# Writes THIRD_PARTY_NOTICES.md: the license text of every third-party Go module linked into the openwarp
# binary, plus the Go standard library. build.sh copies it into OpenWarp.app; CI checks it is current:
#
#   scripts/third-party-notices.sh           regenerate THIRD_PARTY_NOTICES.md
#   scripts/third-party-notices.sh --check   fail if THIRD_PARTY_NOTICES.md is out of date
set -eu
cd "$(dirname "$0")/.."
out=THIRD_PARTY_NOTICES.md
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

license_file() {   # first LICENSE/COPYING-style file in a directory
  for f in LICENSE LICENSE.md LICENSE.txt COPYING; do
    [ -f "$1/$f" ] && { echo "$1/$f"; return; }
  done
  echo "no license file in $1" >&2
  exit 1
}

{
  echo "# Third-party notices"
  echo
  echo "OpenWarp is MIT licensed (see LICENSE). The \`openwarp\` binary, which is also embedded in OpenWarp.app,"
  echo "includes the following third-party code. Generated by \`scripts/third-party-notices.sh\`; do not edit."
  echo
  echo "## Go standard library and runtime"
  echo
  echo '```'
  cat "$(go env GOROOT)/LICENSE"
  echo '```'
  # The modules linked into the universal macOS binary, whatever platform this runs on.
  for arch in arm64 amd64; do
    GOOS=darwin GOARCH=$arch go list -deps \
      -f '{{if not .Standard}}{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}}{{end}}{{end}}{{end}}' ./cmd/openwarp
  done | sort -u | while read -r path version; do
      dir=$(go mod download -json "$path@$version" | sed -n 's/^[[:space:]]*"Dir": "\(.*\)",$/\1/p')
      echo
      echo "## $path $version"
      echo
      echo '```'
      cat "$(license_file "$dir")"
      echo '```'
    done
} > "$tmp"

if [ "${1:-}" = "--check" ]; then
  if ! cmp -s "$tmp" "$out"; then
    echo "$out is out of date: run scripts/third-party-notices.sh and commit the result" >&2
    diff -u "$out" "$tmp" | head -40 >&2 || true
    exit 1
  fi
  echo "$out is up to date"
else
  mv "$tmp" "$out"
  trap - EXIT
  echo "wrote $out"
fi
